def receipt_schedule(rows, origin_at, origin_monotonic_ns=None):
 """Preserve capture order; elapsed time uses one monotonic clock domain.

 Legacy captures lacking monotonic timing stay explicit estimates. Mixed
 clocks cannot silently turn a later receipt into an earlier executable quote.
 """
 rows=tuple(rows);origin=datetime.fromisoformat(origin_at)
 present=[r.get('monotonic_ns') is not None for r in rows]
 if any(present) and (not all(present) or origin_monotonic_ns is None):
  raise ValueError('Incomplete monotonic receipt timing')
 use_monotonic=bool(rows) and all(present);last=origin;result=[];sequence=None
 for row in rows:
  seq=row.get('sequence')
  if seq is not None and sequence is not None and seq<=sequence:
   raise ValueError('Receipt sequence moved backwards or repeated')
  if seq is not None:sequence=seq
  at=(origin+timedelta(microseconds=(row['monotonic_ns']-origin_monotonic_ns)/1000)
      if use_monotonic else datetime.fromisoformat(row['received_at']))
  # Receipt sequence is authoritative for ties and concurrent queue insertion.
  at=max(last,at);result.append((at,row));last=at
 return tuple(result)


